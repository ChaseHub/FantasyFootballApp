describe('weekly-recaps', () => {
  it('compiles Week Crown, Bad Beat, Boom Player, and copyable markdown for past weeks', () => {
    const dash = mockDashboard();
    const recap = buildWeeklyRecap({
      week: 1,
      dashboard: dash,
      trades: [],
      moves: [],
      resolvePlayer: (id) => ({
        name: id === 'p1' ? 'Josh Allen' : 'Player Two',
        position: 'QB',
        nflTeam: 'BUF',
      }),
    });

    expect(recap).toBeTruthy();
    expect(recap?.highScore?.teamName).toBe('Alpha');
    expect(recap?.heartbreaker?.teamName).toBe('Beta');
    expect(recap?.boomPlayers[0]?.name).toBe('Josh Allen');
    expect(recap?.chatMarkdown).toContain('Week Crown: Alpha');

    const champs = buildSeasonWeekChampions(dash);
    expect(champs.length).toBe(1);
    expect(champs[0].week).toBe(1);
  });
});
